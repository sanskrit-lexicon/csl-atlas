// ---- deterministic PRNG (mulberry32) --------------------------------------
function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function randInt(rng, n) {
  return Math.floor(rng() * n);
}

function round(value, digits = 4) {
  if (!Number.isFinite(value)) return null;
  return Number(value.toFixed(digits));
}

// ---- TSV parsing ----------------------------------------------------------
function parseTsv(text) {
  const lines = text.replace(/\r\n/g, "\n").split("\n").filter((l) => l.length > 0);
  const header = lines[0].split("\t");
  return lines.slice(1).map((line) => {
    const cells = line.split("\t");
    const row = {};
    header.forEach((h, i) => (row[h] = cells[i] ?? ""));
    return row;
  });
}

// ---- matrix construction --------------------------------------------------
// Returns dict list (rows), text list (cols), and the weighted + binary maps.
export function buildMatrix(edgeRows, nodeRows) {
  const nodeByText = new Map();
  for (const r of nodeRows) {
    nodeByText.set(r.canonical_text, {
      text: r.canonical_text,
      total: Number(r.total_cites) || 0,
      nDicts: Number(r.n_dicts) || 0,
      variants: r.variant_forms || ""
    });
  }

  // Weighted counts per (dict, text) and per-dict distinct-text sets.
  const dictSet = new Set();
  const textSet = new Set();
  const weight = new Map(); // key `${dict}\t${text}` -> count
  for (const e of edgeRows) {
    const dict = e.dict;
    const text = e.canonical_text;
    const count = Number(e.count) || 0;
    if (!dict || !text) continue;
    dictSet.add(dict);
    textSet.add(text);
    const key = `${dict}\t${text}`;
    weight.set(key, (weight.get(key) || 0) + count);
  }

  const dicts = [...dictSet];
  const texts = [...textSet];

  // Row (dict) degree = number of distinct texts it cites.
  const dictDegree = new Map(dicts.map((d) => [d, 0]));
  // Column marginals recomputed from THIS graph's 11 dicts (node-table n_dicts
  // may count pre-canonicalisation dicts; recompute for internal consistency).
  const textDictCount = new Map(texts.map((t) => [t, 0]));
  const textTotalInGraph = new Map(texts.map((t) => [t, 0]));
  for (const [key, count] of weight.entries()) {
    const [dict, text] = key.split("\t");
    dictDegree.set(dict, dictDegree.get(dict) + 1);
    textDictCount.set(text, textDictCount.get(text) + 1);
    textTotalInGraph.set(text, textTotalInGraph.get(text) + count);
  }

  // Sort rows by degree desc (broadest apparatus first) — nested order for rows.
  dicts.sort((a, b) => dictDegree.get(b) - dictDegree.get(a) || (a < b ? -1 : 1));
  // Sort cols by dict-count desc, then in-graph total desc — nested order for cols.
  texts.sort(
    (a, b) =>
      textDictCount.get(b) - textDictCount.get(a) ||
      textTotalInGraph.get(b) - textTotalInGraph.get(a) ||
      (a < b ? -1 : 1)
  );

  const dictIndex = new Map(dicts.map((d, i) => [d, i]));
  const textIndex = new Map(texts.map((t, i) => [t, i]));

  // Binary matrix as row-sets of column indices (rows = dicts).
  const rowSets = dicts.map(() => new Set());
  const weightMatrix = new Map(); // `${ri}\t${ci}` -> count
  for (const [key, count] of weight.entries()) {
    const [dict, text] = key.split("\t");
    const ri = dictIndex.get(dict);
    const ci = textIndex.get(text);
    rowSets[ri].add(ci);
    weightMatrix.set(`${ri}\t${ci}`, count);
  }

  return {
    dicts,
    texts,
    dictDegree,
    textDictCount,
    textTotalInGraph,
    nodeByText,
    rowSets,
    weightMatrix,
    dictIndex,
    textIndex
  };
}

// ---- NODF nestedness (Almeida-Neto et al. 2008) ---------------------------
// rowSets: array of Set<colIndex>. nCols columns. Column marginals recomputed
// from rowSets. NODF's DF term uses the marginal comparison directly, so it is
// order-independent.
export function nodf(rowSets, nCols) {
  const nRows = rowSets.length;
  const rowMarg = rowSets.map((s) => s.size);

  // Column bitmasks over rows (<=32 rows) + degrees.
  const colMask = new Int32Array(nCols);
  const colDeg = new Int32Array(nCols);
  for (let r = 0; r < nRows; r += 1) {
    const bit = 1 << r;
    for (const c of rowSets[r]) {
      colMask[c] |= bit;
      colDeg[c] += 1;
    }
  }

  let sum = 0;
  // Row pairs.
  for (let i = 0; i < nRows; i += 1) {
    for (let j = i + 1; j < nRows; j += 1) {
      const mi = rowMarg[i];
      const mj = rowMarg[j];
      if (mi === mj) continue; // DF = 0
      const hi = mi > mj ? i : j;
      const lo = mi > mj ? j : i;
      const mlo = rowMarg[lo];
      if (mlo === 0) continue;
      let shared = 0;
      const small = rowSets[lo];
      const big = rowSets[hi];
      for (const c of small) if (big.has(c)) shared += 1;
      sum += (100 * shared) / mlo;
    }
  }
  // Column pairs (bitmask popcount).
  for (let i = 0; i < nCols; i += 1) {
    const di = colDeg[i];
    if (di === 0) continue;
    const mi = colMask[i];
    for (let j = i + 1; j < nCols; j += 1) {
      const dj = colDeg[j];
      if (di === dj || dj === 0) continue;
      const mlo = di < dj ? di : dj;
      const inter = mi & colMask[j];
      // popcount of an <=32-bit int
      let v = inter - ((inter >> 1) & 0x55555555);
      v = (v & 0x33333333) + ((v >> 2) & 0x33333333);
      const shared = (((v + (v >> 4)) & 0x0f0f0f0f) * 0x01010101) >> 24;
      sum += (100 * shared) / mlo;
    }
  }

  const denom = (nRows * (nRows - 1)) / 2 + (nCols * (nCols - 1)) / 2;
  return sum / denom;
}

// ---- Barber bipartite modularity via label propagation --------------------
// Maximise Q = (1/E) sum_{i,j: same module} (A_ij - k_i d_j / E) over row-node
// (dict) and col-node (text) module assignments. LPAwb+ core (Beckett 2016):
// alternately move each node to the module maximising its modularity gain.
export function modularity(rowSets, nCols, rng) {
  const nRows = rowSets.length;
  const rowDeg = rowSets.map((s) => s.size);
  const E = rowDeg.reduce((a, b) => a + b, 0);
  if (E === 0) return { q: 0, nModules: 0 };

  // Column adjacency: rows touching each col.
  const colRows = Array.from({ length: nCols }, () => []);
  const colDeg = new Int32Array(nCols);
  for (let r = 0; r < nRows; r += 1) {
    for (const c of rowSets[r]) {
      colRows[c].push(r);
      colDeg[c] += 1;
    }
  }
  const activeCols = [];
  for (let c = 0; c < nCols; c += 1) if (colDeg[c] > 0) activeCols.push(c);

  function runOnce(rowLabelInit, colLabelInit, nextLabelStart) {
    const rowLabel = rowLabelInit.slice();
    const colLabel = colLabelInit.slice();
    // Module aggregate degrees: K_L (sum row degree), D_L (sum col degree).
    const K = new Map();
    const D = new Map();
    const bump = (map, key, delta) => {
      const v = (map.get(key) || 0) + delta;
      if (v === 0) map.delete(key);
      else map.set(key, v);
    };
    for (let r = 0; r < nRows; r += 1) bump(K, rowLabel[r], rowDeg[r]);
    for (const c of activeCols) bump(D, colLabel[c], colDeg[c]);

    let nextLabel = nextLabelStart;

    let improved = true;
    let guard = 0;
    while (improved && guard < 100) {
      improved = false;
      guard += 1;

      // Update rows.
      for (let r = 0; r < nRows; r += 1) {
        const cur = rowLabel[r];
        bump(K, cur, -rowDeg[r]);
        const nbr = new Map();
        for (const c of rowSets[r]) {
          const L = colLabel[c];
          nbr.set(L, (nbr.get(L) || 0) + 1);
        }
        let bestL = nextLabel; // fresh singleton scores 0
        let bestScore = 0;
        for (const [L, edges] of nbr.entries()) {
          const score = edges - (rowDeg[r] * (D.get(L) || 0)) / E;
          if (score > bestScore + 1e-12) {
            bestScore = score;
            bestL = L;
          }
        }
        if (bestL === nextLabel) nextLabel += 1;
        if (bestL !== cur) improved = true;
        rowLabel[r] = bestL;
        bump(K, bestL, rowDeg[r]);
      }

      // Update cols.
      for (const c of activeCols) {
        const cur = colLabel[c];
        bump(D, cur, -colDeg[c]);
        const nbr = new Map();
        for (const r of colRows[c]) {
          const L = rowLabel[r];
          nbr.set(L, (nbr.get(L) || 0) + 1);
        }
        let bestL = nextLabel;
        let bestScore = 0;
        for (const [L, edges] of nbr.entries()) {
          const score = edges - (colDeg[c] * (K.get(L) || 0)) / E;
          if (score > bestScore + 1e-12) {
            bestScore = score;
            bestL = L;
          }
        }
        if (bestL === nextLabel) nextLabel += 1;
        if (bestL !== cur) improved = true;
        colLabel[c] = bestL;
        bump(D, bestL, colDeg[c]);
      }
    }

    // Q = e_within/E - (sum_L K_L D_L)/E^2
    let eWithin = 0;
    for (let r = 0; r < nRows; r += 1) {
      for (const c of rowSets[r]) if (rowLabel[r] === colLabel[c]) eWithin += 1;
    }
    const labels = new Set([...rowLabel, ...activeCols.map((c) => colLabel[c])]);
    let kd = 0;
    for (const L of labels) kd += (K.get(L) || 0) * (D.get(L) || 0);
    const q = eWithin / E - kd / (E * E);
    return { q, nModules: labels.size };
  }

  let best = { q: -Infinity, nModules: 0 };
  for (let attempt = 0; attempt < LPA_RESTARTS; attempt += 1) {
    const rowLabelInit = rowSets.map((_, r) => r);
    const colLabelInit = new Array(nCols).fill(-1);
    let nextLabelStart = nRows;
    for (const c of activeCols) {
      if (attempt === 0) {
        // Attempt 0: every col its own module (finest partition).
        colLabelInit[c] = nextLabelStart;
        nextLabelStart += 1;
      } else {
        // Later attempts: seed each col to a random neighbour-row's label.
        const rows = colRows[c];
        colLabelInit[c] = rowLabelInit[rows[randInt(rng, rows.length)]];
      }
    }
    const res = runOnce(rowLabelInit, colLabelInit, nextLabelStart);
    if (res.q > best.q) best = res;
  }
  return best;
}

// ---- degree-preserving (fixed-fixed) null via trial swaps -----------------
function cloneRowSets(rowSets) {
  return rowSets.map((s) => new Set(s));
}
// One successful trial swap: pick two rows, exchange an exclusive column of
// each. Preserves every row degree and every column degree exactly.
function trySwap(rowSets, rng) {
  const nRows = rowSets.length;
  const r1 = randInt(rng, nRows);
  let r2 = randInt(rng, nRows);
  if (r1 === r2) r2 = (r2 + 1) % nRows;
  const s1 = rowSets[r1];
  const s2 = rowSets[r2];
  const excl1 = [];
  for (const c of s1) if (!s2.has(c)) excl1.push(c);
  if (excl1.length === 0) return false;
  const excl2 = [];
  for (const c of s2) if (!s1.has(c)) excl2.push(c);
  if (excl2.length === 0) return false;
  const c1 = excl1[randInt(rng, excl1.length)];
  const c2 = excl2[randInt(rng, excl2.length)];
  s1.delete(c1);
  s1.add(c2);
  s2.delete(c2);
  s2.add(c1);
  return true;
}

export function permutationTest(matrix, rng) {
  const { rowSets, texts } = matrix;
  const nCols = texts.length;
  const E = rowSets.reduce((a, s) => a + s.size, 0);

  const obsNodf = nodf(rowSets, nCols);
  const obsMod = modularity(rowSets, nCols, mulberry32(SEED ^ 0x1234));

  const nullMatrix = cloneRowSets(rowSets);
  // Burn-in.
  let done = 0;
  const burnIn = 20 * E;
  while (done < burnIn) if (trySwap(nullMatrix, rng)) done += 1;

  const nodfNull = [];
  const modNull = [];
  const perSample = E; // successful swaps between samples
  let nodfGE = 0;
  let modGE = 0;
  for (let s = 0; s < N_NULL; s += 1) {
    let sw = 0;
    while (sw < perSample) if (trySwap(nullMatrix, rng)) sw += 1;
    const nv = nodf(nullMatrix, nCols);
    const mv = modularity(nullMatrix, nCols, mulberry32((SEED ^ (0x9e3779b1 * (s + 1))) >>> 0)).q;
    nodfNull.push(nv);
    modNull.push(mv);
    if (nv >= obsNodf) nodfGE += 1;
    if (mv >= obsMod.q) modGE += 1;
  }

  const stat = (values) => {
    const m = values.reduce((a, b) => a + b, 0) / values.length;
    const sd = Math.sqrt(values.reduce((a, b) => a + (b - m) * (b - m), 0) / values.length);
    return { mean: m, sd };
  };
  const nStat = stat(nodfNull);
  const mStat = stat(modNull);

  return {
    nodf: {
      observed: round(obsNodf, 3),
      nullMean: round(nStat.mean, 3),
      nullSd: round(nStat.sd, 3),
      z: nStat.sd > 0 ? round((obsNodf - nStat.mean) / nStat.sd, 2) : null,
      p: round((nodfGE + 1) / (N_NULL + 1), 4),
      nNull: N_NULL
    },
    modularity: {
      observed: round(obsMod.q, 4),
      nModules: obsMod.nModules,
      nullMean: round(mStat.mean, 4),
      nullSd: round(mStat.sd, 4),
      z: mStat.sd > 0 ? round((obsMod.q - mStat.mean) / mStat.sd, 2) : null,
      p: round((modGE + 1) / (N_NULL + 1), 4),
      nNull: N_NULL
    }
  };
}

// ---- page-facing views ----------------------------------------------------
function buildViews(matrix) {
  const { dicts, texts, dictDegree, textDictCount, textTotalInGraph, nodeByText, weightMatrix, dictIndex, textIndex, rowSets } = matrix;

  // Top-N texts (already in nested order).
  const topTexts = texts.slice(0, TOP_TEXTS).map((t) => {
    const node = nodeByText.get(t);
    return {
      text: t,
      totalCites: node ? node.total : textTotalInGraph.get(t),
      inGraphCites: textTotalInGraph.get(t),
      nDicts: textDictCount.get(t),
      variants: node ? node.variants : ""
    };
  });

  // Heatmap cells: dict × top-N text citation counts (0 when absent).
  const heatmapCells = [];
  for (const d of dicts) {
    const ri = dictIndex.get(d);
    for (const tt of topTexts) {
      const ci = textIndex.get(tt.text);
      const count = weightMatrix.get(`${ri}\t${ci}`) || 0;
      heatmapCells.push({ dict: d, text: tt.text, count });
    }
  }

  // Canon curve: number of texts cited by exactly k dicts, k = maxDicts..1.
  const byK = new Map();
  for (const t of texts) {
    const k = textDictCount.get(t);
    byK.set(k, (byK.get(k) || 0) + 1);
  }
  const maxK = dicts.length;
  const canonCurve = [];
  for (let k = maxK; k >= 1; k -= 1) canonCurve.push({ nDicts: k, texts: byK.get(k) || 0 });

  // Per-dict fingerprint: breadth + coverage of the shared core (top-20 texts).
  const coreTexts = texts.slice(0, 20).map((t) => textIndex.get(t));
  const perDict = dicts.map((d) => {
    const ri = dictIndex.get(d);
    const cited = rowSets[ri];
    let totalCites = 0;
    for (const ci of cited) totalCites += weightMatrix.get(`${ri}\t${ci}`) || 0;
    const coreHit = coreTexts.filter((ci) => cited.has(ci)).length;
    const top = [...cited]
      .map((ci) => ({ text: texts[ci], count: weightMatrix.get(`${ri}\t${ci}`) || 0 }))
      .sort((a, b) => b.count - a.count || (a.text < b.text ? -1 : 1))
      .slice(0, 5);
    return {
      dict: d,
      distinctTexts: dictDegree.get(d),
      totalCites,
      coreCoverage: round(coreHit / coreTexts.length, 3),
      coreHits: coreHit,
      coreSize: coreTexts.length,
      topTexts: top
    };
  });

  return { topTexts, heatmapCells, canonCurve, perDict, nestedDictOrder: dicts };
}

