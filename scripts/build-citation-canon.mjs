// Build the citation-canon topology packet (PH1 / CANON-CORE) + the V1 page data.
//
// The <ls> citation graph (data/citations/) records which canonical text each
// dictionary cites and how often — a bipartite dict×text matrix. A50 asserts a
// SHARED canon impressionistically; PH1 CANON-CORE tests the matrix TOPOLOGY:
// is it NESTED (each dictionary's cited texts are approximately a subset of the
// next-broader dictionary's — one canon in additive strata) or MODULAR (dicts
// fall into disjoint tradition communities)?
//
// Method (agenda §2 PH1, §4 Dror et al. protocol): on the binarised 11×912
// matrix compute
//   - NODF nestedness (Almeida-Neto et al. 2008), and
//   - Barber (2007) bipartite modularity Q, optimised by label propagation
//     (LPAwb+ core, Beckett 2016),
// each against >=1,000 degree-preserving (fixed-fixed) permutation nulls
// generated by trial-swap randomisation; permutation p reported per stat.
//
// Deterministic: seeded PRNG, generatedAtForPayload idiom. Pure derivation from
// two committed TSVs; no source/corpus read, no human decision.
//
// Usage: npm run build-citation-canon   (then npm run validate-citation-canon)

