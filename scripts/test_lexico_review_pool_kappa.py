"""Fixture tests for the pool-v1 alpha report tool (H5483/B8) — two-model mode.

The committed report docs/REVIEW_POOL_KAPPA_REPORT.md is generated by
scripts/lexico/review_pool_kappa.py; until this file existed nothing executed
that tool in CI (`npm run test-review-pool-kappa` only exercised the separate
Cohen's-kappa utility in scripts/review_pool_kappa.py). Coverage here is the
mechanical contract the U4 measurement rests on:

  * Krippendorff's alpha at the boundaries (perfect, chance-level, degenerate),
  * the two-model join (Pass A packet decisions x Pass B blind labels),
  * the pre-registered gate ladder (CLEAR / DEMOTE / BLOCK / provisional-unstable),
  * per-stratum grouping, the evidence-presence split and the sensitivity
    exclusion, so no figure can be silently changed by an edit to the builder.

Run: python -m unittest scripts.test_lexico_review_pool_kappa
"""
import importlib.util
import random
import unittest
from pathlib import Path

MODULE_PATH = Path(__file__).with_name("lexico") / "review_pool_kappa.py"
SPEC = importlib.util.spec_from_file_location("lexico_review_pool_kappa", MODULE_PATH)
KAPPA = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(KAPPA)

PATHS = {"a": "a.json", "b": "b.json", "blind": "blind.json", "flip": "flip.json"}


def packet(decisions, allowed=("true-low", "parser-gap")):
    """Pass A: review-packet shaped payload (reviewedValue per reviewed-ok row)."""
    return {"sampleRows": [{"reviewId": rid, "reviewedValue": label, "reviewStatus": "reviewed-ok"}
                           for rid, label in decisions.items()]}


def blind_pass(labels, allowed=("true-low", "parser-gap")):
    """Pass B: the committed second-annotator file shape."""
    return {
        "model": {"tier": "Fixture Model", "exactId": "fixture-1"},
        "preRegistration": "docs/PROTOCOL_FIXTURE.md",
        "items": [{"item": i + 1, "reviewId": rid, "label": label, "allowed": list(allowed)}
                  for i, (rid, label) in enumerate(labels.items())],
    }


def build(decisions_a, labels_b, allowed=("true-low", "parser-gap"), blind=None, flip=None):
    return KAPPA.two_model_packet(
        "fixture", packet(decisions_a), blind_pass(labels_b, allowed),
        blind, flip, "fixture-pass-a", random.Random(7), PATHS,
    )


class AlphaTests(unittest.TestCase):
    def test_perfect_agreement_is_one(self):
        units = [["a", "a"], ["b", "b"], ["a", "a"]]
        self.assertEqual(KAPPA.krippendorff_alpha_nominal(units), 1.0)

    def test_degenerate_single_class_is_undefined_not_one(self):
        self.assertIsNone(KAPPA.krippendorff_alpha_nominal([["a", "a"], ["a", "a"]]))

    def test_empty_units_are_undefined(self):
        self.assertIsNone(KAPPA.krippendorff_alpha_nominal([]))

    def test_single_key_rows_contribute_nothing(self):
        self.assertIsNone(KAPPA.krippendorff_alpha_nominal([["a"], ["a"]]))

    def test_gate_clear_needs_ci_low_floor(self):
        outcome, _ = KAPPA.gate_band(0.91, [0.85, 0.95], 2.0)
        self.assertEqual(outcome, "CLEAR")

    def test_gate_demote_between_floors(self):
        outcome, _ = KAPPA.gate_band(0.65, [0.54, 0.76], 0.0)
        self.assertEqual(outcome, "DEMOTE")

    def test_gate_block_below_point_floor(self):
        outcome, _ = KAPPA.gate_band(0.31, [0.10, 0.44], 0.0)
        self.assertEqual(outcome, "BLOCK")

    def test_flip_rate_above_ceiling_is_provisional_unstable(self):
        outcome, reason = KAPPA.gate_band(0.95, [0.90, 0.99], 12.5)
        self.assertEqual(outcome, "PROVISIONAL-UNSTABLE")
        self.assertIn("12.5", reason)

    def test_undefined_alpha_has_no_gate(self):
        outcome, _ = KAPPA.gate_band(None, None, None)
        self.assertEqual(outcome, "UNDEFINED")


class TwoModelJoinTests(unittest.TestCase):
    def test_join_keeps_only_rows_present_in_both_passes(self):
        report = build({"r1": "true-low", "r2": "parser-gap", "r3": "true-low"},
                       {"r1": "true-low", "r2": "parser-gap"})
        self.assertEqual(report["rows"], 2)
        self.assertEqual(report["observedAgreement"], 1.0)
        self.assertEqual(report["krippendorffAlpha"], 1.0)

    def test_disagreements_are_listed_with_both_labels(self):
        report = build({"r1": "true-low", "r2": "parser-gap"},
                       {"r1": "parser-gap", "r2": "parser-gap"})
        self.assertEqual(len(report["disagreements"]), 1)
        row = report["disagreements"][0]
        self.assertEqual((row["reviewId"], row["passA"], row["passB"]), ("r1", "true-low", "parser-gap"))

    def test_every_row_lands_in_a_named_stratum(self):
        skd = ("true-low", "variant-headword", "prose-present", "parser-gap")
        report = build({"r1": "true-low"}, {"r1": "true-low"}, allowed=skd)
        self.assertEqual(report["byStratum"][0]["stratum"], "skd-false-low")

    def test_unmapped_label_set_is_named_not_dropped(self):
        report = build({"r1": "x", "r2": "y"}, {"r1": "x", "r2": "y"}, allowed=("x", "y"))
        self.assertEqual(report["byStratum"][0]["stratum"], "unmapped")

    def test_evidence_presence_split(self):
        blind = {"items": [{"reviewId": "r1", "evidence": [{"excerpt": "…"}]},
                           {"reviewId": "r2", "evidence": []}]}
        report = build({"r1": "true-low", "r2": "true-low"},
                       {"r1": "true-low", "r2": "parser-gap"}, blind=blind)
        split = {row["evidence"]: row["n"] for row in report["byEvidencePresence"]}
        self.assertEqual(split, {"excerpt present": 1, "no excerpt": 1})

    def test_sensitivity_exclusion_changes_the_denominator(self):
        pass_b = blind_pass({"r1": "true-low", "r2": "parser-gap"})
        pass_b["sensitivityExclusions"] = [{"item": 1, "reason": "contaminated"}]
        report = KAPPA.two_model_packet(
            "fixture", packet({"r1": "parser-gap", "r2": "parser-gap"}), pass_b,
            None, None, "fixture-pass-a", random.Random(7), PATHS,
        )
        self.assertEqual(report["rows"], 2)
        self.assertEqual(report["sensitivity"][0]["n"], 1)

    def test_flip_rate_is_carried_into_the_gate(self):
        a = {"r1": "true-low", "r2": "parser-gap", "r3": "true-low", "r4": "parser-gap"}
        b = {"r1": "true-low", "r2": "parser-gap", "r3": "true-low", "r4": "true-low"}
        report = build(a, b, flip={"flipRatePct": 20.0, "flips": 2, "rowRunPairs": 10, "subsampleSize": 5})
        self.assertIsNotNone(report["krippendorffAlpha"])
        self.assertEqual(report["gate"]["outcome"], "PROVISIONAL-UNSTABLE")

    def test_channel_label_is_always_model_x_model(self):
        self.assertEqual(build({"r1": "true-low"}, {"r1": "true-low"})["channel"], "model x model")


if __name__ == "__main__":
    unittest.main()
