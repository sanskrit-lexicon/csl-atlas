"""Markdown renderer for the review-pool alpha report.

Split out of scripts/lexico/review_pool_kappa.py to stay inside the repo's
5 000-token file budget (Uprava tools/token_size_gate).
"""
from __future__ import annotations

from pool_kappa_stats import BOOTSTRAP_RESAMPLES


def render_markdown(payload):
    lines = [
        "# Review Pool v1 — κ Report",
        "",
        "Date: " + payload["generatedAt"][:10],
        "",
        ("Status: generated machine-reviewed analysis over the community review pool's "
        "double-keyed decisions; see docs/REVIEW_POOL_V1_DESIGN.md §9."),
        "",
        "## Chart Trust Block",
        "",
        ("- Claim: Inter-annotator reliability of the community review pool's double-keyed "
        "packets, reported per packet with Krippendorff's alpha as the headline statistic."),
        f"- Evidence label: `{payload['evidenceLabel']}`",
        "- Source files: " + ", ".join(f"`{p}`" for p in payload["sourceFiles"]),
        f"- Generated by: `{payload['generatedBy']}`",
        ("- Validation: `npm run test-review-pool-kappa` (fixture-checked alpha/kappa); "
        "wired into `npm run verify`."),
        ("- Known false positives: a rotating-partner dyad below n=30 has its Cohen's kappa "
        "suppressed, not fabricated."),
        ("- Known false negatives: alpha is undefined (reported `null`) when every key in a "
        "packet falls in one category (degenerate agreement), including the current synthetic "
        "all-approve dry-run canary."),
        f"- Review status: `{payload['reviewStatus']}`",
        f"- Owner repo: `{payload['ownerRepo']}`",
        ("- Next action: the model × model channel is measured — see the two-model sections; the "
        "human × model channel still needs recruited annotators (design §10 P6), and the agenda's "
        "61-row human residue remains an outstanding ask, not a label set."),
        "- External dependencies: none.",
        ("- Boundary note: derived from committed pool merge reports and the committed two-model "
        "pass files only; no source/corpus read, no public page, no recruitment or consent handling."),
        "",
        "## Method",
        "",
        payload["method"],
        "",
    ]
    for packet in payload["packets"]:
        lines += [
            f"## {packet['packetId']}",
            "",
            (f"Rows: {packet['rows']} ({packet['rowsDoubleKeyed']} double-keyed, "
            f"{packet['rowsSingleKey']} single-key)."),
            "",
            "| Statistic | Value |",
            "|---|---|",
            f"| Observed agreement | {packet['observedAgreement']} |",
            f"| Chance-expected agreement | {packet['chanceAgreement']} |",
            f"| Modal-label share | {packet['modalLabelShare']} |",
            f"| Krippendorff's α (nominal) | {packet['krippendorffAlpha']} |",
            f"| α 95% CI (bootstrap, n={BOOTSTRAP_RESAMPLES}) | {packet['alphaCI95']} |",
            f"| Band | `{packet['band']}` |",
            f"| Button-level (approve/reject/defer) agreement | {packet['buttonLevelAgreement']} |",
            f"| Disagreements queued for adjudication | {packet['disagreements']} |",
            f"| Adjudicated | {packet['adjudicated']} |",
            f"| Blocked by adjudicator | {packet['blockedByAdjudicator']} |",
            "",
            "| Dyad | n | Cohen's κ | Band |",
            "|---|---:|---:|---|",
        ]
        for dyad in packet["cohenKappaByDyad"]:
            lines.append(f"| {' × '.join(dyad['dyad'])} | {dyad['n']} | {dyad['kappa']} | `{dyad['band']}` |")
        if packet["expertBaseline"]:
            eb = packet["expertBaseline"]
            lines += ["", (f"Expert baseline (`{eb['sourceFile']}`, n={eb['n']}): "
                          f"pool-key agreement {eb['agreementWithPool']} (never mixed into the pool-internal α).")]
        lines += ["", "**Limitations for this packet:**", ""]
        lines += [f"- {x}" for x in packet["limitations"]]
        lines.append("")
    for pair in payload.get("twoModelPackets", []):
        gate = pair["gate"]
        flip = pair.get("flipRate") or {}
        lines += [
            f"## {pair['packetId']} — cross-model agreement (channel: `{pair['channel']}`)",
            "",
            "| Quantity | Value |",
            "|---|---|",
            f"| Channel | `{pair['channel']}` |",
            f"| Pass A | {pair['passA']['model']} |",
            f"| Pass B | {pair['passB']['model'].get('tier', 'unrecorded')} "
            f"(`{pair['passB']['model'].get('exactId', 'unrecorded')}`) |",
            f"| Rows scored (n) | {pair['rows']} — {pair['denominator']} |",
            f"| Observed agreement | {pair['observedAgreement']} |",
            f"| Krippendorff's α (nominal) | {pair['krippendorffAlpha']} |",
            f"| α 95% CI (bootstrap, n={BOOTSTRAP_RESAMPLES}) | {pair['alphaCI95']} |",
            f"| Landis–Koch band | `{pair['band']}` |",
            f"| Flip-rate (Pass B) | {pair['flipRatePct']} % "
            f"({flip.get('flips', 0)} flips over {flip.get('rowRunPairs', 0)} row×run pairs, "
            f"n={flip.get('subsampleSize', 0)}) |",
            f"| Gate verdict (§4 ladder, L0) | **{gate['outcome']}** — {gate['reason']} |",
            f"| Disagreements | {len(pair['disagreements'])} rows |",
            "",
            "### Per-stratum (descriptive, not gated)",
            "",
            "| Stratum | n | α | 95% CI |",
            "|---|---:|---:|---|",
        ]
        for row in pair["byStratum"]:
            lines.append(f"| {row['stratum']} | {row['n']} | {row['alpha']} | {row['alphaCI95']} |")
        if pair["byEvidencePresence"]:
            lines += [
                "",
                "### Evidence-presence split",
                "",
                "| Packet evidence | n | α | 95% CI |",
                "|---|---:|---:|---|",
            ]
            for row in pair["byEvidencePresence"]:
                lines.append(f"| {row['evidence']} | {row['n']} | {row['alpha']} | {row['alphaCI95']} |")
        if pair["sensitivity"]:
            lines += ["", "### Sensitivity", ""]
            for row in pair["sensitivity"]:
                lines.append(
                    f"- Excluding item(s) {row['excludedItems']} ({row['reason']}): "
                    f"α = {row['alpha']}, 95% CI {row['alphaCI95']}, n = {row['n']}."
                )
        if pair["disagreements"]:
            lines += ["", "Disagreement rows (committed for codebook repair):", ""]
            for row in pair["disagreements"]:
                lines.append(f"- `{row['reviewId']}` ({row['stratum']}): Pass A `{row['passA']}` vs Pass B `{row['passB']}`")
        lines += ["", "**Limitations for this measurement:**", ""]
        lines += [f"- {x}" for x in pair["limitations"]]
        lines.append("")
    lines += ["## Report-level limitations", ""] + [f"- {x}" for x in payload["limitations"]]
    lines += ["", "_Auto-generated by `python scripts/lexico/review_pool_kappa.py`._", ""]
    return "\n".join(lines)
